export function getScreen(id: string): Screen | undefined {
  return screens.find((screen) => screen.id === id);
}

export function screensInCity(slug: string): Screen[] {
  return screens.filter((screen) => screen.citySlug === slug);
}

export function cityName(slug: string): string {
  return getCity(slug)?.name ?? slug;
}

export function measuredScreens(list: Screen[] = screens): Screen[] {
  return list.filter((screen) => screen.widthFt != null && screen.heightFt != null);
}

export function screensForPin(pin: string): Screen[] {
  const digits = pin.replace(/\D/g, "");
  if (digits.length !== 6) return [];
  return screens.filter((screen) => screen.pin === digits || screen.address.includes(digits));
}

export function brandsInUse(): Screen["brand"][] {
  const seen = new Set<Screen["brand"]>();
  for (const screen of screens) seen.add(screen.brand);
  return [...seen];
}
